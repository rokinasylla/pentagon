"""
Outil de détection de WAF / CDN pour PENTAGON.

Cet outil identifie la présence d'un pare-feu applicatif (WAF) ou d'un CDN
devant la cible, avec un focus sur Cloudflare. Il ne cherche PAS à contourner
la protection : il la *cartographie*. Savoir qu'un WAF est présent (et lequel)
conditionne la stratégie des agents en aval :
- interprétation correcte des réponses (un 403 « Cloudflare » n'est pas un 403
  applicatif),
- pertinence de la recherche d'IP d'origine (cf. origin_discovery_tool),
- calibrage des tests applicatifs.

Utilisé par : Agent Scanning (PTES phase 3 — identification des couches de défense)
Standards :
- OWASP WSTG-INFO-02 (Fingerprint Web Server / Infrastructure)
- MITRE ATT&CK T1590.006 (Gather Victim Network Information: Network Security Appliances)

Niveau de risque : ACTIF mais très léger (1 requête HTTP).
"""

from datetime import datetime, timezone
from typing import Any

# `requests` est importé de façon DIFFÉRÉE dans run_waf_detection (seule fonction
# à faire du réseau), pour que ce module s'importe hors-ligne — la couche pure
# analyze_waf_signals reste ainsi testable sans dépendance réseau (convention PENTAGON).


DEFAULT_TIMEOUT = 20
DEFAULT_HEADERS = {"User-Agent": "PENTAGON-Scanning-Agent/1.0"}

# Combien d'octets de corps on inspecte pour repérer une page de challenge.
BODY_SNIPPET_LEN = 4096


# Signatures de WAF/CDN reconnues, indexées par fournisseur.
# On distingue trois familles d'indices :
# - "headers"        : nom d'en-tête dont la simple présence trahit le fournisseur
# - "header_values"  : (nom_header, sous-chaîne) à chercher dans une valeur d'en-tête
# - "cookies"        : préfixe de cookie caractéristique
# - "body_markers"   : chaîne caractéristique d'une page de blocage/challenge
WAF_SIGNATURES: dict[str, dict[str, Any]] = {
    "Cloudflare": {
        "headers": ["cf-ray", "cf-cache-status", "cf-mitigated"],
        "header_values": [("server", "cloudflare")],
        "cookies": ["__cfduid", "__cf_bm", "cf_clearance"],
        "body_markers": [
            "attention required",
            "cloudflare",
            "cf-chl",
            "cf-browser-verification",
            "challenge-platform",
        ],
    },
    "Akamai": {
        "headers": ["x-akamai-transformed", "akamai-grn"],
        "header_values": [("server", "akamaighost")],
        "cookies": ["ak_bmsc", "akamai"],
        "body_markers": ["access denied", "akamai"],
    },
    "AWS (CloudFront/WAF)": {
        "headers": ["x-amz-cf-id", "x-amz-cf-pop"],
        "header_values": [("server", "cloudfront"), ("server", "awselb")],
        "cookies": ["awsalb", "awsalbcors"],
        "body_markers": ["request blocked", "generated by cloudfront"],
    },
    "Imperva/Incapsula": {
        "headers": ["x-iinfo", "x-cdn"],
        "header_values": [("x-cdn", "incapsula")],
        "cookies": ["incap_ses", "visid_incap"],
        "body_markers": ["incapsula incident id", "powered by incapsula"],
    },
    "Sucuri": {
        "headers": ["x-sucuri-id", "x-sucuri-cache"],
        "header_values": [("server", "sucuri")],
        "cookies": [],
        "body_markers": ["sucuri website firewall", "access denied - sucuri"],
    },
    "F5 BIG-IP ASM": {
        "headers": [],
        "header_values": [("server", "big-ip")],
        "cookies": ["ts", "bigipserver"],
        "body_markers": ["the requested url was rejected"],
    },
}

# Codes/état qui, combinés à une signature, suggèrent un blocage actif du WAF
# plutôt qu'une simple présence en coupure.
CHALLENGE_STATUS_CODES = {403, 406, 429, 503}


def analyze_waf_signals(
    headers: dict[str, str],
    status_code: int | None,
    body_snippet: str,
    cookies: list[str] | None = None,
) -> dict[str, Any]:
    """
    Analyse (PURE, sans réseau) des signaux HTTP pour détecter un WAF/CDN.

    Isolée de toute I/O pour être testable hors-ligne : on lui passe des
    en-têtes, un code HTTP et un extrait de corps déjà récupérés.

    Args:
        headers: en-têtes de la réponse (les clés seront normalisées en minuscules).
        status_code: code HTTP de la réponse (peut être None).
        body_snippet: début du corps de la réponse (texte).
        cookies: noms de cookies posés par la réponse (Set-Cookie).

    Returns:
        Dict avec :
        - waf_detected (bool)
        - vendors (list[str]) : fournisseurs identifiés, du plus au moins probable
        - is_cloudflare (bool)
        - blocking (bool) : la réponse ressemble-t-elle à un blocage/challenge actif
        - evidence (list[dict]) : indices concrets (fournisseur, type, valeur)
    """
    headers_lower = {str(k).lower(): str(v) for k, v in (headers or {}).items()}
    body_lower = (body_snippet or "").lower()
    cookie_names = [c.lower() for c in (cookies or [])]

    # Score par fournisseur pour ordonner les résultats par confiance.
    scores: dict[str, int] = {}
    evidence: list[dict[str, str]] = []

    def _add(vendor: str, weight: int, kind: str, detail: str) -> None:
        scores[vendor] = scores.get(vendor, 0) + weight
        evidence.append({"vendor": vendor, "type": kind, "value": detail})

    for vendor, sig in WAF_SIGNATURES.items():
        for header_name in sig.get("headers", []):
            if header_name.lower() in headers_lower:
                _add(vendor, 3, "header", header_name)

        for header_name, needle in sig.get("header_values", []):
            value = headers_lower.get(header_name.lower(), "")
            if needle.lower() in value.lower():
                _add(vendor, 3, "header_value", f"{header_name}: {value}")

        for cookie_prefix in sig.get("cookies", []):
            if any(name.startswith(cookie_prefix.lower()) for name in cookie_names):
                _add(vendor, 2, "cookie", cookie_prefix)

        for marker in sig.get("body_markers", []):
            if marker.lower() in body_lower:
                _add(vendor, 1, "body_marker", marker)

    # Ordonne les fournisseurs par score décroissant.
    vendors = [v for v, _ in sorted(scores.items(), key=lambda kv: kv[1], reverse=True)]

    is_cloudflare = "Cloudflare" in scores
    # Un blocage actif = signature présente ET code de type challenge, ou un
    # marqueur de challenge dans le corps.
    challenge_body = any(
        e["type"] == "body_marker" and e["vendor"] in scores for e in evidence
    )
    blocking = bool(vendors) and (
        (status_code in CHALLENGE_STATUS_CODES) or challenge_body
    )

    return {
        "waf_detected": bool(vendors),
        "vendors": vendors,
        "is_cloudflare": is_cloudflare,
        "blocking": blocking,
        "evidence": evidence,
    }


def run_waf_detection(
    target_url: str,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict[str, Any]:
    """
    Détecte le WAF/CDN devant une cible via une unique requête HTTP.

    Args:
        target_url: URL ou domaine de la cible (https:// ajouté si absent).
        timeout: délai d'attente réseau.

    Returns:
        Dict structuré : status, target_url, http_status, waf_detected, vendors,
        is_cloudflare, blocking, evidence, server_header, duration_seconds, error.
    """
    import requests  # import différé : garde le module importable hors-ligne

    started_at = datetime.now(timezone.utc)

    if not target_url.startswith("http"):
        target_url = f"https://{target_url}"

    result: dict[str, Any] = {
        "status": "success",
        "target_url": target_url,
        "http_status": None,
        "waf_detected": False,
        "vendors": [],
        "is_cloudflare": False,
        "blocking": False,
        "evidence": [],
        "server_header": None,
        "duration_seconds": None,
        "error": None,
    }

    try:
        response = requests.get(
            target_url,
            timeout=timeout,
            headers=DEFAULT_HEADERS,
            allow_redirects=True,
        )

        cookie_names = [c.name for c in response.cookies]
        body_snippet = response.text[:BODY_SNIPPET_LEN] if response.text else ""

        signals = analyze_waf_signals(
            headers=dict(response.headers),
            status_code=response.status_code,
            body_snippet=body_snippet,
            cookies=cookie_names,
        )

        result["http_status"] = response.status_code
        result["server_header"] = response.headers.get("Server")
        result.update({
            "waf_detected": signals["waf_detected"],
            "vendors": signals["vendors"],
            "is_cloudflare": signals["is_cloudflare"],
            "blocking": signals["blocking"],
            "evidence": signals["evidence"],
        })

    except requests.exceptions.Timeout:
        result["status"] = "error"
        result["error"] = f"Timeout après {timeout}s"
    except requests.exceptions.RequestException as e:
        result["status"] = "error"
        result["error"] = f"Erreur réseau : {type(e).__name__}: {str(e)}"
    except Exception as e:
        result["status"] = "error"
        result["error"] = f"{type(e).__name__}: {str(e)}"

    ended_at = datetime.now(timezone.utc)
    result["duration_seconds"] = (ended_at - started_at).total_seconds()

    return result
